test_that(".supersede moves records aside, never deleting them", {
  dir <- withr::local_tempdir()
  .write_record(dir, list(file = "p001.jpg", status = "ok"))
  .write_record(dir, list(file = "p002.jpg", status = "ok"))
  expect_message(n <- .supersede(dir, c("p001.jpg", "missing.jpg")), "Moved 1 earlier result ")
  expect_identical(n, 1L)
  dest <- list.dirs(file.path(dir, "superseded"), recursive = FALSE)
  expect_true(file.exists(file.path(dest, "p001.json")))
  expect_false(file.exists(file.path(dir, "p001.json")))
  expect_true(file.exists(file.path(dir, "p002.json")))
  expect_match(basename(dest), "^\\d{8}-\\d{6}$")
  # a second record of the same page in the same folder never writes over the first
  .write_record(dir, list(file = "p001.jpg", status = "ok", date = "later"))
  expect_identical(.supersede(dir, "p001.jpg", dest = dest, quiet = TRUE), 1L)
  expect_setequal(list.files(dest), c("p001.json", "p001-1.json"))
  expect_identical(.supersede(NULL, "p001.jpg"), 0L)
  expect_identical(.supersede(dir, character()), 0L)
  expect_identical(.supersede(dir, "missing.jpg", dest = file.path(dir, "nowhere")), 0L)
  expect_false(dir.exists(file.path(dir, "nowhere")))
})

test_that(".results_dir: no folder unless one is named; a named folder is created, leftovers cleared", {
  withr::local_options(amanuensis.ask = TRUE)   # a question would stop a non-interactive run
  dir <- withr::local_tempdir()
  pages <- data.frame(image = file.path(dir, "p001.jpg"), file = "p001.jpg")
  attr(pages, "folder") <- dir
  expect_null(.results_dir(pages, NULL))
  expect_null(.results_dir(pages, FALSE))
  expect_identical(list.files(dir, all.files = TRUE, no.. = TRUE), character())
  named <- file.path(dir, "results", "deep")
  expect_identical(.results_dir(pages, named), .show_path(named))
  expect_true(dir.exists(named))
  writeLines("x", file.path(named, ".amanuensis-tmp123"))
  expect_identical(.results_dir(pages, named), .show_path(named))
  expect_false(file.exists(file.path(named, ".amanuensis-tmp123")))
  expect_error(.results_dir(pages, 3), class = "amanuensis_error")
  expect_error(.results_dir(pages, file.path(.libPaths()[1], "x")), class = "amanuensis_error_input",
               regexp = "package library")
