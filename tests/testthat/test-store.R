test_that("a results folder alone rebuilds the result", {
  local_amanuensis()
  dir <- withr::local_tempdir()
  make_jpegs(file.path(dir, "pages"), 2)
  out <- file.path(dir, "out")
  res <- quietly(transcribe(file.path(dir, "pages"), test_instructions(), roster_codebook(), model = "mock",
                                save_to = out))
  back <- .result_from_folder(out)
  expect_identical(as.data.frame(back), as.data.frame(res))
  expect_identical(.result_info(back)$pages$status, c("ok", "ok"))
  expect_identical(.result_info(back)$codebook$variables, roster_codebook()$variables)
  expect_identical(.as_result(out)$file, res$file)
  expect_identical(.as_result(res), res)
  expect_error(.as_result(42), class = "amanuensis_error_input", regexp = "Expected the result")
  # two contracts in one folder: say which
  quietly(transcribe(file.path(dir, "pages"), test_instructions("Other."), roster_codebook(), model = "mock",
                         save_to = out, only = 1, redo = 1))
  expect_error(.result_from_folder(out), class = "amanuensis_error_contract", regexp = "2 different")
  one <- .result_from_folder(out, contract = .contract(test_instructions("Other."), roster_codebook())$id)
  expect_identical(unique(one$file), "p001.jpg")
  expect_error(.result_from_folder(out, contract = "nope"), class = "amanuensis_error_contract")
  empty <- file.path(dir, "empty")
  dir.create(empty)
  expect_error(.result_from_folder(empty), class = "amanuensis_error_input", regexp = "holds no results")
  expect_error(.result_from_folder(file.path(dir, "none")), class = "amanuensis_error_input", regexp = "Cannot find")
})

