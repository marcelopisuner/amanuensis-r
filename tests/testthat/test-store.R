test_that(".describe_change says what differs in plain words", {
  cb <- roster_codebook()
  a <- .contract_entry(.contract(test_instructions("Line one.\nLine two."), cb))
  b <- .contract_entry(.contract(test_instructions("Line one.\nLine 2."), cb))
  expect_identical(.describe_change(a, b), "instructions: 2 lines changed")
  cb2 <- quietly(codebook(data.frame(variable = c("heading", "name", "parish"), level = c("page", "row", "row"),
                                     description = c("H.", "N.", "P."))))
  c2 <- .contract_entry(.contract(test_instructions("Line one.\nLine two."), cb2))
  ch <- .describe_change(a, c2)
  expect_true("codebook: added parish" %in% ch)
  expect_true("codebook: removed age, sex" %in% ch)
  cb3 <- roster_codebook()
  cb3$schema$properties$heading$description <- "Another description."
  d <- .contract_entry(.contract(test_instructions("Line one.\nLine two."), cb3))
  expect_identical(.describe_change(a, d), "codebook: descriptions, types or values changed")
  e <- a
  e$free_text <- TRUE
  expect_identical(.describe_change(a, e), "codebook: table/free text setting changed")
  expect_identical(.describe_change(a, a), "the package's standard wording changed")
})

